import turtle as t

t.speed(0)
t.color("green")
t.fillcolor("green")


t.penup()
t.goto(-80, 150)
t.pendown()
t.begin_fill()
t.circle(80)
t.end_fill()

t.penup()
t.goto(0, 180)
t.pendown()
t.begin_fill()
t.circle(80)
t.end_fill()

t.penup()
t.goto(80, 150)
t.pendown()
t.begin_fill()
t.circle(80)
t.end_fill()

t.done()

